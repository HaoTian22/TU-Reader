def main():
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    cur = con.cursor()

    # 城市 id -> 城市名
    cur.execute("SELECT city_id, city_name FROM city")
    city_name = {r["city_id"]: r["city_name"] for r in cur.fetchall()}

    cur.execute("SELECT line_id, city_id, line_name, line_color FROM line")
    rows = cur.fetchall()

    updated = matched = 0
    missing = []
    for r in rows:
        key = (city_name[r["city_id"]], r["line_name"])
        color = COLOR.get(key)
        if color is None:
            missing.append(key)
            continue
        if r["line_color"] != color:
            cur.execute("UPDATE line SET line_color=? WHERE line_id=?", (color, r["line_id"]))
            updated += 1
        matched += 1

    con.commit()
    con.close()

    total = len(rows)
    print(f"total rows={total} matched={matched} updated={updated}")
    print(f"left NULL: {total - matched}")
    uniq_missing = sorted(set(missing))
    print("lines without color (left blank):")
    for c, n in uniq_missing:
        print(f"  {c} {n}")


if __name__ == "__main__":
    main()
